function C = pcd_ui_colors()
%PCD_UI_COLORS MATLAB 自己画的控件（uifigure 窗口、仪器设置对话框）的配色。
%
% 配色分两处、各管一半，改主题时两边要一起改：
%   web/app.css   页面内所有元素（面板、按钮、卡片、图表）—— 界面主体
%   本文件        只有 MATLAB 原生部件：uifigure 窗口底色、对话框控件
% 下表右侧注释里的 CSS 变量就是同一个颜色的出处，两边当前取值一致。
%
% 设计原则：中性灰黑打底，只留 1 个强调色（蓝）+ 1 个警示色（红）。
C.fig    = [0.066 0.078 0.098];   % --fig      窗口底色（须与页面底色一致，否则露边）
C.text   = [0.900 0.916 0.936];   % --text     主文字
C.muted  = [0.560 0.600 0.660];   % --muted    说明 / 次要文字
C.editBg = [0.062 0.074 0.092];   % --edit-bg  输入框底
C.editFg = [0.930 0.945 0.960];   % --edit-fg  输入框文字
C.btn    = [0.235 0.420 0.690];   % --btn      强调色（主按钮）
C.btn2   = [0.190 0.215 0.255];   % --btn2     中性次级按钮（取消 / 指派）
C.btnFg  = [1     1     1    ];   % --btn-fg   按钮文字
C.warn   = [1.000 0.500 0.500];   % --warn     无信号等警示文字
end
